def _upload_content_problem(ext: str, data: bytes) -> str | None:
    """Why `data` is not a plain file of the allowlisted type `ext` (`UPLOAD_ALLOWED`), or None. The magic bytes must
    match the extension; Office Open XML must be a macro-free document of its kind (no vbaProject part, no
    macro-enabled content type, no embedded program); OpenDocument must carry its own mimetype and no macros."""
    head = data[:16]
    if ext == "pdf":
        return None if b"%PDF-" in data[:1024] else "not a PDF"
    if ext == "png":
        return None if head.startswith(b"\x89PNG\r\n\x1a\n") else "not a PNG image"
    if ext in ("jpg", "jpeg"):
        return None if head.startswith(b"\xff\xd8\xff") else "not a JPEG image"
    if ext == "gif":
        return None if head[:6] in (b"GIF87a", b"GIF89a") else "not a GIF image"
    if ext == "webp":
        return None if head[:4] == b"RIFF" and head[8:12] == b"WEBP" else "not a WebP image"
    if ext in ("tif", "tiff"):
        return None if head[:4] in (b"II*\x00", b"MM\x00*") else "not a TIFF image"
    if ext == "heic":
        return None if head[4:8] == b"ftyp" and head[8:12] in (b"heic", b"heix", b"hevc", b"heim", b"heis",
                                                                 b"mif1", b"msf1") else "not a HEIC image"
    if ext in ("txt", "csv", "tsv", "json"):
        if data.startswith((b"\xff\xfe", b"\xfe\xff")):  # UTF-16 with its byte order mark
            return None
        return "not a text file (binary content)" if b"\x00" in data else None
    if ext in _OOXML_MAIN or ext in _ODF_MIME:
        import zipfile
        from io import BytesIO

        if not data.startswith(b"PK\x03\x04"):
            return "not an Office / OpenDocument file"
        try:
            with zipfile.ZipFile(BytesIO(data)) as z:
                names = z.namelist()
                lower = [n.replace("\\", "/").lower() for n in names]
                inner = (_dangerous_ext() | UPLOAD_EXTRA_BLOCKED) - {"bin", "svg"}  # printer settings, icons
                if any(n.rsplit(".", 1)[-1] in inner or n.endswith("vbaproject.bin") or n.endswith("vbadata.xml")
                       or n.startswith(("basic/", "scripts/")) for n in lower):
                    return "it carries macros or an embedded program"
                if ext in _OOXML_MAIN:
                    if "[Content_Types].xml" not in names or _OOXML_MAIN[ext] not in names:
                        return f"not a {UPLOAD_ALLOWED[ext]}"
                    with z.open("[Content_Types].xml") as f:
                        types = f.read(1 << 20).lower()
                    if b"macroenabled" in types or b"vbaproject" in types:
                        return "it carries macros"
                    if any(n.startswith(("word/embeddings/", "xl/embeddings/", "ppt/embeddings/"))
                           and n.rsplit(".", 1)[-1] not in ("docx", "xlsx", "pptx", "png", "jpeg", "jpg", "emf", "wmf")
                           for n in lower):
                        return "it carries an embedded object (OLE)"
                else:
                    if not names or names[0] != "mimetype":
                        return f"not an {UPLOAD_ALLOWED[ext]}"
                    with z.open("mimetype") as f:
                        if f.read(200).strip() != _ODF_MIME[ext].encode():
                            return f"not an {UPLOAD_ALLOWED[ext]}"
        except (zipfile.BadZipFile, OSError, KeyError, ValueError, RuntimeError, NotImplementedError):
            return "not a readable Office / OpenDocument file"
        return None
    return "not an allowed type"


def check_upload(filename: str, data: bytes, max_bytes: int) -> str:
    """Refuse a file uploaded from the computer before it is stored: empty, too large for the message
    (base64 adds a third), active content (by extension or executable magic bytes), an e-mail file, any type
    outside the allowlist (`UPLOAD_ALLOWED`: archives, installers, legacy Office, RTF, web pages …), or content that
    does not match its extension (`_upload_content_problem`). Returns the file's base name."""
    from app.mail.inbound import DANGEROUS_EXT

    name = Path(str(filename or "").replace("\\", "/")).name.strip() or "upload"
    _no_ctl(name, "attachment name")
    shown = name[:80]
    raw_ext = name.rpartition(".")[2] if "." in name else ""
    ext = re.sub(r"[^A-Za-z0-9]", "", raw_ext).lower()  # as `_ext` names the attachment
    if name != name.rstrip(". ") or raw_ext.lower() != ext:
        # "tool.exe;", "page.html." or an invisible character after the extension: the name the attachment
        # gets (`_ext`) would not be the extension checked here
        raise ComposeError(f"{shown!r}: the file name ends in an unusual extension; rename the file (letters and "
                           "digits after the last dot) and upload it again", "upload")
    if not data:
        raise ComposeError(f"{shown}: the file is empty", "upload")
    limit = int(max_bytes * 0.74)
    if len(data) > limit:
        raise ComposeError(f"{shown} is {len(data) / 1e6:.1f} MB; one e-mail carries at most "
                           f"{max_bytes / 1e6:.1f} MB in all, so a file may be up to {limit / 1e6:.1f} MB. Submit "
                           "large files through the recipient's portal.", "upload")
    if ext in DANGEROUS_EXT or ext in UPLOAD_EXTRA_BLOCKED or data.startswith(_EXEC_MAGIC):
        raise ComposeError(f"{shown} cannot be attached: {BLOCK_TEXT['dangerous']} (e-mail files too: attach the "
                           "files they carry instead)", "upload")
    if ext not in UPLOAD_ALLOWED:
        raise ComposeError(f"{shown} cannot be attached: only {UPLOAD_ALLOWED_TEXT} are uploaded. Archives (.zip, "
                           ".7z …), installers, programs, scripts, web pages, legacy Office (.doc, .xls, .ppt), RTF, "
                           "macro and e-mail files are refused.", "upload")
    why = _upload_content_problem(ext, data)
    if why is not None:
        raise ComposeError(f"{shown} cannot be attached: {why} — its content does not match a plain "
                           f"{UPLOAD_ALLOWED[ext]} (renamed, or active content). Save it again as a plain "
                           f".{ext} and upload it.", "upload")
    return name


def store_uploads(db: Session, access, corr: Correspondence, files: list[tuple[str, bytes]]) -> list[EvidenceItem]:
    """Store files uploaded on the compose page as R3 evidence (Stop orders & correspondence, sha256,
    the vault), linked to the letter (meta.evidence_ids: they go to this authority only) and listed in
    meta.mail_uploads. Every file is checked before any is stored. Flushes; the caller commits and audits."""
    files = [(n, d) for n, d in files if n or d]
    if not files:
        return []
    if not access.can("add_evidence") or not access.can("prepare_email"):
        raise ComposeError("your role cannot upload attachments", "upload")
    if len(files) > UPLOAD_MAX_FILES:
        raise ComposeError(f"at most {UPLOAD_MAX_FILES} files at once", "upload")
    _vault()
    max_bytes = max_bytes_for(_settings())
    names = [check_upload(n, d, max_bytes) for n, d in files]
    from io import BytesIO

    out: list[EvidenceItem] = []
    for name, (_n, data) in zip(names, files, strict=True):
        try:
            item = ev.store_upload(db, access.case, BytesIO(data), filename=name, folder="stop_orders_correspondence",
                                   title=f"Attachment for letter #{corr.id}: {name}"[:255], source_type="upload",
                                   classification="R3", tags=["aegis-mail", "mail-upload"], actor=access.user,
                                   max_bytes=max_bytes)
        except ev.EvidenceError as e:
            drop_vault_files(out)  # the files stored before this one: no evidence row will hold them
            raise ComposeError(f"{name[:80]} could not be stored: {e}", "upload") from None
        except BaseException:
            drop_vault_files(out)
            raise
        item.meta = {**(item.meta or {}), "mail_upload_for": corr.id}
        out.append(item)
    meta = dict(corr.meta or {})
    ids = [int(i) for i in meta.get("evidence_ids") or [] if str(i).isdigit()]
    meta["evidence_ids"] = ids + [i.id for i in out if i.id not in ids]
    ups = [int(i) for i in meta.get("mail_uploads") or [] if str(i).isdigit()]
    meta["mail_uploads"] = ups + [i.id for i in out if i.id not in ups]
    corr.meta = meta
    db.flush()
    return out


def drop_vault_files(items: list[EvidenceItem]) -> None:
    """Remove the vault files of evidence rows that are being rolled back (never committed)."""
    try:
        root = ev.vault_dir(create=False)
    except ev.EvidenceError:
        return
    for item in items:
        if not item.vault_path:
            continue
        try:
            p = (root / item.vault_path).resolve()
            if p.is_relative_to(root):
                p.unlink(missing_ok=True)
        except OSError:
            pass


def _same_letter(corr: Correspondence):
    """The e-mails of this letter (its letter key, or the correspondence row itself)."""
    return (MailMessage.letter_key == letter_key(corr)) | (MailMessage.correspondence_id == corr.id)


CHECKLIST_OPEN = (MailStatus.PREPARED, MailStatus.EXPIRED)


def is_open_checklist(mm: MailMessage) -> bool:
    """A "Draft — you send" checklist (manual transport) that may still go out from Outlook: prepared or expired,
    never cancelled, superseded or recorded."""
    return mm.transport == "manual" and mm.direction == MailDirection.OUT and mm.status in CHECKLIST_OPEN \
        and not isinstance((mm.meta or {}).get("superseded_by"), int)


def open_checklist(db: Session, corr: Correspondence) -> MailMessage | None:
    """The letter's oldest open "Draft — you send" checklist (`is_open_checklist`), or None. While Aegis sends itself
    one blocks every live e-mail of the letter (`refuse_open_checklist`, mail_send._check_preconditions)."""
    if corr.id is None:
        return None
    rows = db.scalars(select(MailMessage).where(
        _same_letter(corr), MailMessage.direction == MailDirection.OUT, MailMessage.transport == "manual",
        MailMessage.status.in_(CHECKLIST_OPEN)).order_by(MailMessage.id)).all()
    return next((r for r in rows if is_open_checklist(r)), None)


def checklist_text(checklist: MailMessage) -> str:
    return (f"This letter has an Outlook checklist (#{checklist.id}) from before Aegis sent e-mail itself. Open it and "
            "choose: I did not send it from Outlook — retire it, or Record as sent.")


def refuse_open_checklist(db: Session, corr: Correspondence) -> None:
    """While Aegis sends itself, nothing prepares a live e-mail of a letter with an open old checklist
    (ComposeError "checklist", `checklist_text`). Manual mode: the checklist is the current way to send."""
    if is_manual():
        return
    checklist = open_checklist(db, corr)
    if checklist is not None:
        raise ComposeError(checklist_text(checklist), "checklist")


def supersede_prepared(db: Session, access, corr: Correspondence, *, reason: str,
                       pending: list[str] | None = None) -> list[int]:
    """Cancel the prepared previews of this letter that the member may cancel (their own; a case admin:
    every one): after an edit none of them may be sent. Each one by compare-and-swap (`retire_prepared`):
    one that a Send claimed meanwhile is never touched, and the edit is refused (ComposeError "letter"; the
    caller rolls back). The pending files to delete once committed go to `pending`. Returns the cancelled ids."""
    rows = db.scalars(select(MailMessage).where(_same_letter(corr), MailMessage.direction == MailDirection.OUT,
                                                MailMessage.status == MailStatus.PREPARED)).all()
    out = []
    for mm in rows:
        if not (access.can("send_email") or mm.created_by == access.user.id):
            continue
        path = retire_prepared(db, mm, by=access.user.id, reason=reason, edited_away=True)
        if path is None:
            raise ComposeError(f"E-mail #{mm.id} of letter #{corr.id} is being sent right now; nothing was changed. "
                               "Reload the page once it went out (or failed).", "letter")
        if pending is not None:
            pending.append(path)
        out.append(mm.id)
    db.flush()
    return out


def _refuse_busy(db: Session, corr: Correspondence, *, exclude_id: int | None = None) -> None:
    """The letter's text, fields and uploads stay as they are while another e-mail of it is sending, sent or of
    unknown outcome (`letter_in_flight`): what the letter record shows is what went out."""
    busy = letter_in_flight(db, corr, exclude_id=exclude_id)
    if busy is not None:
        raise ComposeError(letter_busy_text(corr, busy), "letter")


def save_compose(db: Session, access, corr: Correspondence, authority, form: dict,
                 uploads: list[tuple[str, bytes]] | None = None) -> SaveResult:
    """The editor's Save (also run before Prepare / Send now): the letter text (`body_markdown`, when the
    form has it), the uploaded files (stored as evidence, attached and ticked) and the e-mail fields
    (meta.mail_draft); the member's prepared previews of the letter are cancelled. Refused when the
    letter changed since the page was opened (`draft_hash`), and while another e-mail of the letter is sending,
    sent or of unknown outcome (`letter_in_flight`: the letter's text stays what went out). Commits; on any
    error the vault files of this save's uploads are removed and the caller rolls back. The caller audits.
    `form` gets the new draft hash and the uploads' attachment refs, ready for `prepare`."""
    _check_draft(access, corr)
    if not access.can("prepare_email"):
        raise ComposeError("your role cannot prepare e-mails", "form")
    refuse_pointless(db, corr)
    _refuse_busy(db, corr)
    refuse_open_checklist(db, corr)
    if (form.get("draft_hash") or "") != draft_hash(corr):
        raise ComposeError("the letter changed while you were editing (another tab or member); reload the page and "
                           "apply your changes again", "draft")
    res = SaveResult()
    body = None
    if "body_markdown" in form:
        body = str(form.get("body_markdown") or "").replace("\r\n", "\n").replace("\r", "\n")
        if not body.strip():
            raise ComposeError("the letter text cannot be empty", "body")
        if len(body) > BODY_MAX:
            raise ComposeError(f"the letter text is longer than {BODY_MAX:,} characters", "body")
        if _BODY_CTL.search(body):
            raise ComposeError("the letter text contains control characters", "body")
        if body != (corr.body_markdown or "") and not access.can("draft_letter"):
            raise ComposeError("your role cannot edit the letter text", "body")
    subject = strip_tag(access.case, corr, str(form.get("subject") or "").strip())
    _no_ctl(subject, "subject")
    if len(subject) > SUBJECT_MAX:
        raise ComposeError(f"the subject is longer than {SUBJECT_MAX} characters", "subject")
    for key in ("to_other", "cc_other", "bcc_other"):
        if any(c in str(form.get(key) or "") for c in "\r\x00"):
            raise ComposeError("an address cannot contain line breaks", key.split("_")[0])
    pending: list[str] = []
    try:
        # the prepared previews (compare-and-swap: one a Send claimed meanwhile refuses the save) …
        res.superseded = supersede_prepared(db, access, corr, reason="the e-mail was edited", pending=pending)
        res.uploaded = store_uploads(db, access, corr, list(uploads or []))
        if body is not None:
            res.body_changed = desk.update_body(db, corr, body, actor=access.user, source="mail_compose")
        refs = list(dict.fromkeys([*_split(form.get("attach")), *(f"evidence:{i.id}" for i in res.uploaded)]))
        form["attach"] = refs
        meta = dict(corr.meta or {})
        meta["mail_draft"] = {"to": _split(form.get("to")), "cc": _split(form.get("cc")),
                              "to_other": _clean_other(form.get("to_other")),
                              "cc_other": _clean_other(form.get("cc_other")),
                              "bcc_other": _clean_other(form.get("bcc_other")), "subject": subject, "attach": refs,
                              "saved_at": _now().isoformat(), "by": access.user.id,
                              **({"cc_add": [k for k in _split(form.get("cc_add")) if k in CC_OFFER_KEYS]}
                                 if form.get("cc_offered") else {})}
        corr.meta = meta
        _refuse_busy(db, corr)  # … and once more before committing: another member's preview may have gone out
        db.commit()
    except BaseException as e:
        drop_vault_files(res.uploaded)  # rolled back by the caller: no evidence row keeps these bytes
        if isinstance(e, desk.DeskError) and not isinstance(e, ComposeError):
            raise ComposeError(str(e), "body") from None
        raise
    for path in pending:
        unlink_pending(path)
    res.draft_hash = form["draft_hash"] = draft_hash(corr)
    return res


EDITABLE = (MailStatus.PREPARED, MailStatus.EXPIRED, MailStatus.FAILED, MailStatus.CANCELLED)


def reopen_for_edit(db: Session, access, mm: MailMessage, corr: Correspondence) -> bool:
    """Prepared state → the editor: the e-mail's fields (recipients incl. Bcc, subject, attachments) go
    back into the letter's meta.mail_draft and a prepared preview is cancelled (its MIME deleted), so it
    can never be sent; the compose page then shows every field as prepared. Returns True when a
    prepared preview was cancelled. Refused for an e-mail that was sent (or may have been), while another
    e-mail of the letter is sending / sent / of unknown outcome, while Aegis sends and the letter has an open old
    checklist (`refuse_open_checklist`), and when a Send claimed this one meanwhile (the cancel is a
    compare-and-swap: `retire_prepared`)."""
    if mm.case_id != access.case.id or mm.direction != MailDirection.OUT or mm.correspondence_id != corr.id:
        raise LookupError("message not found")
    if mm.status not in EDITABLE:
        raise ComposeError(f"this e-mail is {mm.status.value}; only an unsent e-mail is edited", "form")
    if mm.status == MailStatus.PREPARED and not (access.can("send_email") or mm.created_by == access.user.id):
        raise ComposeError("only the member who prepared it or a case admin may edit this e-mail", "forbidden")
    _check_draft(access, corr)
    if not access.can("prepare_email"):
        raise ComposeError("your role cannot prepare e-mails", "forbidden")
    _refuse_busy(db, corr)
    refuse_open_checklist(db, corr)
    form = renew_form(mm, access.case, corr)
    if mm.transport == "manual" and not is_manual():
        _drop_mailbox(form)  # a retired checklist may copy the case mailbox; Aegis now sends from it
    path = None
    if mm.status == MailStatus.PREPARED:
        path = retire_prepared(db, mm, by=access.user.id, reason="reopened for editing", edited_away=True)
        if path is None:
            db.rollback()
            raise ComposeError(f"E-mail #{mm.id} is being sent right now (or was meanwhile); nothing was changed.",
                               "form")
    _fold_cc_offers(db, access, form)
    _write_saved_draft(corr, form, access.user.id, from_message=mm.id)
    db.commit()
    unlink_pending(path)
    return path is not None


def mailbox_copied(mm: MailMessage) -> bool:
    """A "Draft — you send" checklist that copied (Cc / Bcc) the case mailbox, which Aegis now sends from."""
    mailbox = (_settings().mail_from or "").strip().lower()
    return bool(mailbox) and mailbox in {a.lower() for a in [*(mm.cc_addrs or []), *bcc_of(mm)]}


def _drop_mailbox(form: dict) -> None:
    """Take the case mailbox out of a `renew_form`'s Cc / Bcc (it cannot be a recipient of its own message)."""
    mailbox = (_settings().mail_from or "").strip().lower()
    if mailbox:
        form["cc"] = [a for a in form["cc"] if a.strip().lower() != mailbox]
        form["bcc_other"] = ", ".join(a for a in _split(form["bcc_other"]) if a.lower() != mailbox)


def _write_saved_draft(corr: Correspondence, form: dict, user_id: int, **extra) -> None:
    """The editor's saved fields (meta.mail_draft) from a `renew_form` of a prepared e-mail."""
    meta = dict(corr.meta or {})
    meta["mail_draft"] = {"to": list(form["to"]), "cc": list(form["cc"]), "to_other": "", "cc_other": "",
                          "bcc_other": form["bcc_other"], "subject": form["subject"], "attach": list(form["attach"]),
                          "saved_at": _now().isoformat(), "by": user_id,
                          **({"cc_add": list(form["cc_add"])} if "cc_add" in form else {}), **extra}
    corr.meta = meta


SENT_ITEMS_FOLDER = "sentitems"


def outlook_send_suspected(db: Session, mm: MailMessage) -> MailMessage | None:
    """A message the mailbox sync read from Sent Items, sent after this manual-mode checklist was prepared, that may be
    this letter sent from Outlook and is waiting for review (app.mail.sync_outbound step 6: ambiguous, or tied to the
    case only by metadata): logged on this case for the same authority (or no authority), or unassigned with this case
    among its candidates. None when there is none (a recorded send makes the letter busy instead)."""
    since = mm.prepared_at if mm.prepared_at is None or mm.prepared_at.tzinfo else mm.prepared_at.replace(tzinfo=UTC)
    key = (mm.meta or {}).get("authority_key")
    q = select(MailMessage).where(MailMessage.direction == MailDirection.OUT, MailMessage.folder == SENT_ITEMS_FOLDER,
                                  MailMessage.id != mm.id,
                                  (MailMessage.case_id == mm.case_id) | MailMessage.case_id.is_(None))
    if since is not None:
        q = q.where(MailMessage.sent_at.is_(None) | (MailMessage.sent_at >= since))
    for r in db.scalars(q.order_by(MailMessage.id.desc())):
        meta = r.meta or {}
        if not meta.get("needs_review"):
            continue
        if r.case_id == mm.case_id and (key is None or r.authority_key in (None, key)):
            return r
        if r.case_id is None and mm.case_id in {int(c) for c in meta.get("candidate_case_ids") or []
                                               if str(c).isdigit()}:
            return r
    return None


def sent_items_coverage(db: Session, report, mm: MailMessage) -> str:
    """Whether the mailbox sync `report` (app.mail.ingest.SyncReport, a run without errors) could have seen this
    checklist sent from Outlook: "ok" when it read Sent Items without errors and that folder's backfill start
    (mail_sync_folders.since: AEGIS_MAIL_INBOUND_SINCE, the mailbox's cutover, or a "Backfill since") is no later than
    the checklist's preparation (the sync skips anything sent before `since`, app.mail.sync_outbound); else
    "no_sent_items" (Sent Items was not read: a file / demo inbound transport, or its read failed) or
    "before_cutover" (Sent Items is read only from after the checklist was prepared)."""
    from app.db.models import MailSyncFolder

    if SENT_ITEMS_FOLDER not in (report.folders or []) or (report.sent or {}).get("errors") or not report.mailbox:
        return "no_sent_items"
    fs = db.get(MailSyncFolder, (report.mailbox, SENT_ITEMS_FOLDER))
    if fs is None:
        return "no_sent_items"
    since = fs.since if fs.since is None or fs.since.tzinfo else fs.since.replace(tzinfo=UTC)
    prepared = mm.prepared_at if mm.prepared_at is None or mm.prepared_at.tzinfo else \
        mm.prepared_at.replace(tzinfo=UTC)
    if since is None or prepared is None or since > prepared:
        return "before_cutover"
    return "ok"


class OutlookSendWaiting(ComposeError):
    """`retire_checklist` refused: `seen` (a Sent Items message that may be the checklist) waits for review."""

    def __init__(self, seen: MailMessage):
        when = seen.sent_at.astimezone(UTC).strftime("%d %b %Y %H:%M UTC") if seen.sent_at else "recently"
        super().__init__(f"The mailbox sync found a message sent from Outlook on {when} (e-mail #{seen.id}) that may be "
                         "this letter and is waiting for review. Review it first (tie it to the letter, or dismiss "
                         "it); if it was this letter, use Record as sent. Nothing was retired.", "checklist")
        self.seen = seen


def retire_checklist(db: Session, access, mm: MailMessage, corr: Correspondence) -> bool:
    """"I did not send it from Outlook — retire it" (a case admin, while Aegis sends itself; the route reads Sent Items
    first): an open old checklist (`is_open_checklist`) is cancelled by compare-and-swap with the confirmation recorded
    (meta.not_sent_confirmed), and its fields (case mailbox out of Cc / Bcc) go into the editor (meta.mail_draft).
    Refused when the letter is no longer a draft or an e-mail of it is out (sent, recorded, sending), and
    (OutlookSendWaiting) while a Sent Items message that may be it waits for review (`outlook_send_suspected`). Commits. Returns whether the case mailbox was taken out of Cc / Bcc."""
    if mm.case_id != access.case.id or mm.direction != MailDirection.OUT or mm.correspondence_id != corr.id:
        raise LookupError("message not found")
    if not access.can("send_email"):
        raise ComposeError("only a case admin retires an Outlook checklist", "forbidden")
    if is_manual() or not is_open_checklist(mm):
        raise ComposeError(f"this e-mail is {mm.status.value}; only an open Outlook checklist is retired while Aegis "
                           "sends itself", "form")
    if corr.status != CorrespondenceStatus.DRAFT or letter_in_flight(db, corr) is not None:
        # the Sent Items sync (or Record as sent, another e-mail of it) has the letter as sent meanwhile: an expired
        # checklist of it stays open (only prepared siblings are retired), and "not sent" would contradict that record
        raise ComposeError("this letter was already sent or recorded as sent; nothing was retired", "checklist")
    seen = outlook_send_suspected(db, mm)
    if seen is not None:
        raise OutlookSendWaiting(seen)
    now = _now()
    form = renew_form(mm, access.case, corr)
    _drop_mailbox(form)
    path = retire_prepared(db, mm, by=access.user.id, from_statuses=CHECKLIST_OPEN,
                           reason="retired: not sent from Outlook (a case admin confirmed); Aegis sends the letter",
                           not_sent_confirmed={"by": access.user.id, "at": now.isoformat()})
    if path is None:
        db.rollback()
        raise ComposeError("this checklist changed meanwhile (recorded as sent, cancelled or expired); nothing was "
                           "retired", "form")
    _fold_cc_offers(db, access, form)
    _write_saved_draft(corr, form, access.user.id, from_message=mm.id)  # a draft with nothing in flight (above)
    db.commit()
    unlink_pending(path)
    return mailbox_copied(mm)


# --------------------------------------------------------------------------- preview
@dataclass
class Preview:
    headers: list[tuple[str, str]]
    text: str
    html_markdown: str  # the letter Markdown the HTML part was generated from (rendered with the md filter)
    attachments: list[dict]
    size: int
    sha256: str
    ok: bool = True
    problem: str | None = None
    html: str = ""  # the text/html part verbatim (manual mode: copied to the clipboard as rich text)
    unsent: bool = False  # an X-Unsent draft (manual mode)


def preview(db: Session, mm: MailMessage, corr: Correspondence | None) -> Preview:
    """The stored MIME bytes parsed back: exactly what was (or will be) sent."""
    from email.parser import BytesParser

    try:
        raw = read_raw(mm, db)
    except (OSError, ev.EvidenceError) as e:
        return Preview(headers=[], text="", html_markdown="", attachments=list(mm.attachments or []),
                       size=mm.mime_size or 0, sha256=mm.mime_sha256 or "", ok=False, problem=str(e)[:200])
    msg = BytesParser(policy=policy.default).parsebytes(raw)
    headers = [(h, str(msg[h])) for h in ("From", "To", "Cc", "Reply-To", "Subject", "Date", "Message-ID",
                                          "In-Reply-To") if msg[h] is not None]
    body = msg.get_body(preferencelist=("plain",))
    text = body.get_content() if body is not None else ""
    html_part = msg.get_body(preferencelist=("html",))
    html = html_part.get_content() if html_part is not None else ""
    parsed = {}
    for part in msg.iter_attachments():
        data = part.get_payload(decode=True) or b""
        parsed[part.get_filename() or ""] = {"type": part.get_content_type(), "size": len(data),
                                             "sha256": hashlib.sha256(data).hexdigest()}
    atts = []
    for m in mm.attachments or []:
        p = parsed.get(m.get("filename") or "", {})
        atts.append({**m, "parsed_type": p.get("type"), "parsed_size": p.get("size"), "parsed_sha256": p.get("sha256"),
                     "matches": p.get("sha256") == m.get("sha256")})
    sha = hashlib.sha256(raw).hexdigest()
    ok = sha == mm.mime_sha256
    return Preview(headers=headers, text=text,
                   html_markdown=outbound_markdown(corr.body_markdown if corr is not None else ""),
                   attachments=atts, size=len(raw), sha256=sha, ok=ok,
                   problem=None if ok else "the stored bytes no longer match the prepared hash", html=html,
                   unsent=str(msg.get("X-Unsent") or "").strip() == "1")


# --------------------------------------------------------------------------- manual mode: send it yourself
def verified_raw(mm: MailMessage, db: Session | None = None) -> bytes:
    """The prepared bytes, refused (EvidenceError) when they no longer match the prepared sha256."""
    raw = read_raw(mm, db)
    if mm.mime_sha256 and hashlib.sha256(raw).hexdigest() != mm.mime_sha256:
        raise ev.EvidenceError("the stored bytes no longer match the prepared hash")
    return raw


def attachment_parts(raw: bytes) -> list[tuple[str, str, bytes]]:
    """(neutral file name, MIME type, bytes) of every attachment of a stored message, in order."""
    from email.parser import BytesParser

    msg = BytesParser(policy=policy.default).parsebytes(raw)
    out = []
    taken: set[str] = set()
    for part in msg.iter_attachments():
        name = safe_filename(part.get_filename() or "attachment", taken)
        out.append((name, part.get_content_type(), part.get_payload(decode=True) or b""))
    return out


def attachments_zip(parts: list[tuple[str, str, bytes]]) -> bytes:
    """Every attachment in one .zip (stored file names are the neutral ones; fixed timestamps)."""
    import io
    import zipfile

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as z:
        for name, _mime, data in parts:
            info = zipfile.ZipInfo(name, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o600 << 16
            z.writestr(info, data)
    return buf.getvalue()


def mailto_url(to: list[str], cc: list[str], subject: str, text: str, bcc: list[str] | None = None) -> str | None:
    """A mailto: link for a short letter (None when the URL would be longer than MAILTO_MAX: mail
    clients truncate long ones). It carries no attachments and plain text only."""
    from urllib.parse import quote

    query = [f"subject={quote(subject or '', safe='')}", f"body={quote(text or '', safe='')}"]
    if cc:
        query.insert(0, f"cc={quote(','.join(cc), safe='@,')}")
    if bcc:
        query.insert(1 if cc else 0, f"bcc={quote(','.join(bcc), safe='@,')}")
    url = f"mailto:{quote(','.join(to), safe='@,')}?" + "&".join(query)
    return url if len(url) <= MAILTO_MAX else None
