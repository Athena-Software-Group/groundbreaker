@dataclass
class SenderCheck:
    problem: str | None  # None | no_profile | body_mismatch | from_name
    text: str = ""
    expected: str | None = None
    fixable: bool = False  # the editor's "Use the sender profile's signature" rewrites the opening and the close

    @property
    def ok(self) -> bool:
        return self.problem is None

    @property
    def needs_ack(self) -> bool:
        """Send needs the case admin's acknowledgement (one tick): the letter or the From name says another sender.
        No sender profile is an information note only."""
        return self.problem in ("body_mismatch", "from_name")


def _flat(text: str) -> str:
    return " ".join((text or "").split()).lower()


def sender_check(db: Session, case, corr: Correspondence | None, settings=None) -> SenderCheck:
    """Is the letter signed as the sender of record ("<org>, on behalf of <victim>", the case's sender
    profile) that the From header (the Athena mailbox) implies? Module doc."""
    from app.domain import sender as sender_mod

    settings = settings if settings is not None else _settings()
    from_name = (getattr(settings, "from_name", "") or "").strip()
    mailbox = getattr(settings, "mail_from", "") or "the case mailbox"
    profile = sender_mod.get_profile(db, case)
    body = _flat(markdown_to_text(corr.body_markdown if corr is not None else ""))
    if profile is None:
        firm = str(((case.facts or {}).get("investigator") or {}).get("firm") or "").strip()
        signed = f"; the letter text is signed by {firm}" if firm and _flat(firm) in body else ""
        return SenderCheck("no_profile", f"This case has no sender profile yet: e-mails go out as "
                           f"{from_name or sender_mod.org_name()} ({mailbox}){signed}. Set up the sender profile (who "
                           "signs, on whose behalf, contact e-mail) so new letters are signed the same way.")
    expected = f"{profile.org_name or sender_mod.org_name()}, on behalf of {profile.on_behalf_of}"
    other_firm = PI_FIRM_PHRASE in body
    if _flat(expected) not in body or other_firm:
        return SenderCheck("body_mismatch", "The letter text was not written with this case's sender profile ("
                           + ("it carries another firm's block" if other_firm else f"it does not read “{expected}”")
                           + "): it was probably generated before the profile was set up or changed. Use the sender "
                           "profile's signature (one click in the editor), or send it as it is with the "
                           "acknowledgement.", expected, fixable=True)
    if from_name and _flat(from_name) != _flat(profile.org_name or sender_mod.org_name()):
        return SenderCheck("from_name", f"The e-mail's From name is “{from_name}” but the letter is "
                           f"signed by “{profile.org_name}”. Align the sender profile with "
                           "AEGIS_MAIL_FROM_NAME, or send it as it is with the acknowledgement.", expected)
    return SenderCheck(None, "", expected)


_INTRO_RE = re.compile(r"^(?:we write as |we write on behalf of )", re.IGNORECASE)
_CLOSING_RE = re.compile(r"^(?:yours (?:faithfully|sincerely|respectfully|truly)|(?:with )?(?:kind |best |warm )?regards|"
                         r"sincerely|respectfully|thank you|many thanks|best wishes)\s*,?\s*$", re.IGNORECASE)


def with_profile_signature(body: str, intro: str, signature: str) -> str:
    """`body` (a letter's Markdown) opening and closing as the sender profile writes them: its opening paragraph ("We
    write as …", "We write on behalf of …", another firm's "… is a private investigations and intelligence firm")
    becomes `intro` (inserted after the salutation when there is none), and everything from its last closing
    ("Yours faithfully," …) to the end becomes `signature` (added when there is none). The internal provenance
    footer, and anything after it, stays as it is."""
    text = (body or "").replace("\r\n", "\n").replace("\r", "\n")
    m = _FOOTER_RE.search(text)
    main, tail = (text[:m.start()], text[m.start():]) if m else (text, "")
    paras = [p for p in re.split(r"\n[ \t]*\n", main.strip()) if p.strip()]

    def plain(p: str) -> str:
        return _flat(markdown_to_text(p))

    at = next((i for i, p in enumerate(paras) if _INTRO_RE.match(plain(p)) or PI_FIRM_PHRASE in plain(p)), None)
    if at is not None:
        paras[at] = intro
    else:
        dear = next((i for i, p in enumerate(paras) if plain(p).startswith("dear ")), None)
        paras.insert(dear + 1 if dear is not None else 0, intro)
        at = dear + 1 if dear is not None else 0
    # a closing may share its paragraph with the name under it ("Yours respectfully,\nJ. Smith"): its first line
    close = next((i for i in range(len(paras) - 1, at, -1)
                  if _CLOSING_RE.match(plain(paras[i].strip().splitlines()[0]))), None)
    paras = (paras[:close] if close is not None else paras) + [signature]
    out = "\n\n".join(p.strip("\n") for p in paras).rstrip() + "\n"
    return out + ("\n" + tail.lstrip("\n") if tail.strip() else "")


def profile_signature_body(db: Session, case, body: str) -> str | None:
    """`body` with the case's sender-profile opening and signature (`with_profile_signature`), or None without a
    profile."""
    from app.domain import sender as sender_mod

    profile = sender_mod.get_profile(db, case)
    if profile is None:
        return None
    return with_profile_signature(body, *sender_mod.letter_parts(case, profile))


