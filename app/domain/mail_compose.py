def letter_key(corr: Correspondence) -> str:
    """The letter an e-mail carries: a stop order's own letter is the stop order (it may be drafted
    on more than one correspondence row); any other letter is its correspondence row."""
    from app.db.models import CorrespondenceKind

    if corr.kind == CorrespondenceKind.STOP_ORDER and corr.stop_order_id:
        return f"o{int(corr.stop_order_id)}"
    return f"c{int(corr.id)}"


def stale_draft_left(mm: MailMessage) -> bool:
    """A failed e-mail whose unsent draft may still be in the mailbox (failed by an earlier version
    of reconcile, before it deleted drafts): the letter is not prepared again until it is gone."""
    return mm.status == MailStatus.FAILED and mm.error_reason == "unsent_draft" \
        and bool((mm.meta or {}).get("mailbox_draft")) and not (mm.meta or {}).get("draft_deleted")


def letter_in_flight(db: Session, corr: Correspondence, *, exclude_id: int | None = None) -> MailMessage | None:
    """Another outbound e-mail of the same letter that is sending, sent or of unknown outcome, or
    that failed leaving an unsent draft in the mailbox (`stale_draft_left`)."""
    same = (MailMessage.letter_key == letter_key(corr)) | (MailMessage.correspondence_id == corr.id)
    q = select(MailMessage).where(MailMessage.direction == MailDirection.OUT, MailMessage.status.in_(LETTER_BUSY), same)
    if exclude_id is not None:
        q = q.where(MailMessage.id != exclude_id)
    busy = db.scalars(q.order_by(MailMessage.id.desc()).limit(1)).first()
    if busy is not None:
        return busy
    q = select(MailMessage).where(MailMessage.direction == MailDirection.OUT, MailMessage.status == MailStatus.FAILED,
                                  MailMessage.error_reason == "unsent_draft", same)
    if exclude_id is not None:
        q = q.where(MailMessage.id != exclude_id)
    return next((m for m in db.scalars(q.order_by(MailMessage.id.desc())).all() if stale_draft_left(m)), None)


def letter_busy_text(corr: Correspondence, other: MailMessage) -> str:
    st = other.status.value
    if other.status == MailStatus.SENT_EXTERNAL:
        when = other.sent_at.astimezone(UTC).strftime("%d %b %Y %H:%M UTC") if other.sent_at else "earlier"
        return (f"Letter #{corr.id} was sent outside Aegis ({when}; recorded as e-mail #{other.id}). Aegis records one "
                "e-mail per letter; to write to the recipient again, generate a follow-up letter.")
    if other.status == MailStatus.SENT:
        return (f"Letter #{corr.id} already went out as e-mail #{other.id}. Aegis sends one e-mail per letter; to "
                "write to the recipient again, generate a follow-up letter.")
    if other.status == MailStatus.UNKNOWN:
        return (f"E-mail #{other.id} of letter #{corr.id} may already have been sent (outcome unknown). Open it and "
                "use “Check the mailbox now”: only that check can mark it sent or failed. Nothing else "
                "is sent for this letter until then.")
    if stale_draft_left(other):
        return (f"E-mail #{other.id} of letter #{corr.id} failed but left an unsent draft in the mailbox. Open it and "
                "use “Check the mailbox now” to delete that draft first: the letter is not prepared again while "
                "a draft of it may still be in the mailbox.")
    return f"E-mail #{other.id} of letter #{corr.id} is {st}; nothing else is sent for this letter meanwhile."


