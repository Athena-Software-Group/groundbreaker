def _tlp_marked(value: str | None) -> bool:
    v = (value or "").strip().upper()
    return v.startswith("TLP:RED") or v.startswith("TLP:AMBER")


def tlp_blocked(item: EvidenceItem, db: Session | None = None) -> bool:
    """TLP:RED / TLP:AMBER (incl. +STRICT) on the item, any of its tags, or any parent (recursively)."""
    seen: set[int] = set()
    cur: EvidenceItem | None = item
    while cur is not None and cur.id not in seen:
        seen.add(cur.id)
        if _tlp_marked(cur.tlp) or any(_tlp_marked(str(t)) for t in cur.tags or []):
            return True
        if not cur.parent_id:
            break
        from sqlalchemy.orm import object_session

        session = db or object_session(cur)
        cur = session.get(EvidenceItem, cur.parent_id) if session is not None else None
    return False


