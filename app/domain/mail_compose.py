def build_mime(*, from_name: str, mail_from: str, to: list[str], cc: list[str], subject: str, text_body: str,
               html_body: str, attachments: list[tuple[str, str, bytes]], message_id: str,
               in_reply_to: str | None = None, references: str | None = None,
               date: datetime | None = None, unsent: bool = False, bcc: list[str] | None = None) -> tuple[bytes, str]:
    """The raw RFC 5322 message: multipart/mixed [multipart/alternative [text/plain, text/html],
    attachments…]. No Bcc and no X-headers carrying case data. Returns (raw bytes, Message-ID).

    `unsent=True` (manual mode) builds an editable draft instead: `X-Unsent: 1` (the one X-header,
    it carries no case data), no Date, no Message-ID (the sending server sets both: Aegis claims no
    id for a message it never sent), and From / Reply-To only when a mailbox is configured. Only such
    a draft carries `bcc` as a Bcc header (the mail client sends it and strips it); a message Aegis
    sends never does (the transport gets the Bcc addresses separately)."""
    for v, what in ((subject, "subject"), (from_name, "sender name"), (mail_from, "sender address"),
                    (message_id, "message id"), (in_reply_to or "", "in-reply-to"), (references or "", "references")):
        _no_ctl(v, what)
    for a in [*to, *cc, *(bcc or [])]:
        _no_ctl(a, "recipient address")
    for name, _, _ in attachments:
        _no_ctl(name, "attachment name")
    msg = EmailMessage(policy=SEND_POLICY)
    sender_hdr = formataddr((from_name, mail_from)) if mail_from else None
    if unsent:
        msg["X-Unsent"] = "1"
    if sender_hdr:
        msg["From"] = sender_hdr
    msg["To"] = ", ".join(to)
    if cc:
        msg["Cc"] = ", ".join(cc)
    if unsent and bcc:
        msg["Bcc"] = ", ".join(bcc)
    msg["Subject"] = subject
    if not unsent:
        msg["Date"] = format_datetime((date or _now()).astimezone(UTC))
        msg["Message-ID"] = message_id
    if sender_hdr:
        msg["Reply-To"] = sender_hdr
    if in_reply_to:
        msg["In-Reply-To"] = in_reply_to
        msg["References"] = references or in_reply_to
    msg.set_content(text_body, subtype="plain", charset="utf-8")
    msg.add_alternative(html_body, subtype="html", charset="utf-8")
    msg.make_mixed()
    for name, mime, data in attachments:
        maintype, _, subtype = mime.partition("/")
        msg.add_attachment(data, maintype=maintype or "application", subtype=subtype or "octet-stream", filename=name)
    return msg.as_bytes(), message_id


# --------------------------------------------------------------------------- pending files (vault)
def _vault() -> Path:
    try:
        return ev.vault_dir()
    except ev.EvidenceError:
        raise ComposeError("AEGIS_VAULT_DIR must be set: every sent e-mail is filed as evidence", "vault") from None


def _write_pending(case_id: int, raw: bytes) -> str:
    root = _vault()
    d = root / PENDING_DIR / str(int(case_id))
    d.mkdir(mode=0o700, parents=True, exist_ok=True)
    os.chmod(root / PENDING_DIR, 0o700)
    os.chmod(d, 0o700)
    name = f"{uuid.uuid4().hex}.eml"
    fd = os.open(d / name, os.O_WRONLY | os.O_CREAT | os.O_EXCL | getattr(os, "O_NOFOLLOW", 0), 0o600)
    with os.fdopen(fd, "wb") as fh:
        fh.write(raw)
    return f"{PENDING_DIR}/{int(case_id)}/{name}"


def _pending_file(mm: MailMessage) -> Path | None:
    return _pending_path(mm.mime_path)


def _pending_path(mime_path: str | None) -> Path | None:
    if not mime_path:
        return None
    rel = Path(mime_path)
    if rel.is_absolute() or ".." in rel.parts:
        raise ev.EvidenceError("pending mail path escapes the vault")
    root = ev.vault_dir(create=False)
    p = (root / rel).resolve()
    if not p.is_relative_to(root):
        raise ev.EvidenceError("pending mail path escapes the vault")
    return p


def read_raw(mm: MailMessage, db: Session | None = None) -> bytes:
    """The message's exact MIME bytes: the pending vault file, else its .eml evidence item."""
    p = _pending_file(mm)
    if p is not None and p.is_file():
        return p.read_bytes()
    if mm.eml_evidence_id and db is not None:
        item = db.get(EvidenceItem, mm.eml_evidence_id)
        if item is not None:
            return ev.read_verified(item)
    raise ev.EvidenceError("the message bytes are no longer available")


def delete_pending(mm: MailMessage) -> None:
    unlink_pending(mm.mime_path)
    mm.mime_path = None


def unlink_pending(mime_path: str | None) -> None:
    """Delete a pending MIME file by its vault path (after the row that held it was committed retired)."""
    try:
        p = _pending_path(mime_path)
    except ev.EvidenceError:
        p = None
    if p is not None:
        try:
            p.unlink()
        except (FileNotFoundError, OSError):
            pass


def retire_prepared(db: Session, mm: MailMessage, *, by: int | None, reason: str | None = None,
                    status: MailStatus = MailStatus.CANCELLED,
                    from_statuses: tuple[MailStatus, ...] = (MailStatus.PREPARED,), **meta) -> str | None:
    """Compare-and-swap a prepared e-mail to `status` (cancelled / expired): one `UPDATE … WHERE status IN
    from_statuses`, like mail_send._claim, so a Send that claimed the row meanwhile (prepared → sending) is never
    overwritten and its pending MIME is never deleted mid-send. `meta` keys are merged into the row's meta (None
    removes one) with a history line. Returns the pending file's vault path ("" when none) for the caller to
    delete with `unlink_pending` once it committed, or None when the row was no longer in `from_statuses`
    (nothing written). Does not commit; the loaded `mm` mirrors the new state."""
    from sqlalchemy import update
    from sqlalchemy.orm.attributes import set_committed_value

    now = _now()
    new_meta = dict(mm.meta or {})
    for k, v in meta.items():
        if v is None:
            new_meta.pop(k, None)
        else:
            new_meta[k] = v
    new_meta["history"] = list(new_meta.get("history") or []) + [
        {"status": status.value, "at": now.isoformat(), "by": by, **({"reason": reason} if reason else {})}]
    old_path = mm.mime_path or ""
    res = db.execute(update(MailMessage)
                     .where(MailMessage.id == mm.id, MailMessage.status.in_(from_statuses))
                     .values(status=status, mime_path=None, meta=new_meta, updated_at=now)
                     .execution_options(synchronize_session=False))
    if res.rowcount != 1:
        return None
    for attr, value in (("status", status), ("mime_path", None), ("meta", new_meta)):
        set_committed_value(mm, attr, value)
    return old_path


