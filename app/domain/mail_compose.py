def _filed_as_eml_of(item: EvidenceItem, db: Session | None = None) -> list[MailMessage]:
    """The e-mails (in or out) whose filed .eml this item is (MailMessage.eml_evidence_id)."""
    session = _session_of(item, db)
    if session is None or item.id is None:
        return []
    return list(session.scalars(select(MailMessage).where(MailMessage.eml_evidence_id == item.id)).all())


def is_inbound(item: EvidenceItem, db: Session | None = None) -> bool:
    """Received from outside through the case mailbox (the .eml or one of its attachments). Decided
    from provenance the evidence edit form cannot change (meta.mail_message_id, the e-mail it was
    filed as) as well as the mail tags / source type (which ev.update_item keeps for mail items)."""
    tags = {str(t).strip().lower() for t in item.tags or []}
    if tags & INBOUND_TAGS or (item.source_type or "") in INBOUND_SOURCE_TYPES:
        return True
    if mail_message_id_of(item) is not None:
        return True  # only app.mail.ingest sets it, on received e-mails and their attachments
    return any(m.direction == MailDirection.IN for m in _filed_as_eml_of(item, db))


def is_received_email(item: EvidenceItem, db: Session | None = None) -> bool:
    """A whole e-mail received from outside: the raw .eml filed by app.mail.ingest, or an extracted
    attachment that is itself a message (message/rfc822, .eml, .msg). Never attachable, even when
    marked safe: only the non-dangerous files extracted from it can be."""
    tags = {str(t).strip().lower() for t in item.tags or []}
    if "received-email" in tags:
        return True
    if any(m.direction == MailDirection.IN for m in _filed_as_eml_of(item, db)):
        return True
    if not is_inbound(item, db):
        return False
    name = str((item.meta or {}).get("original_filename") or item.title or "").lower()
    mime = (item.mime or "").split(";")[0].strip().lower()
    return (item.source_type or "") == "eml" or mime in ("message/rfc822", "message/global", "application/vnd.ms-outlook") \
        or name.endswith((".eml", ".msg"))


def marked_mail_safe(item: EvidenceItem) -> bool:
    return bool((item.meta or {}).get("mail_safe"))


def static_block_reason(access, item: EvidenceItem, *, max_bytes: int | None = None) -> str | None:
    """Why an evidence item can never be attached (before reading it): tlp, integrity, dangerous,
    received_email (a received raw message: never, even marked safe), inbound (received by e-mail and
    not marked safe by a case admin), financial-not-admin or too_large. None = it may be attached
    (its bytes are re-checked when read). Which authority it may go to is `authority_block_reason`."""
    if tlp_blocked(item):
        return "tlp"
    if ev.integrity_status(item) in ("mismatch", "missing"):
        return "integrity"
    if is_dangerous(item) or _ext(item) in _dangerous_ext():  # also by the extension the attachment would get
        return "dangerous"
    if is_received_email(item):
        return "received_email"
    if is_inbound(item) and not marked_mail_safe(item):
        return "inbound"
    if item.folder == EvidenceFolder.FINANCIAL and not ev.allowed(access, "view_financial"):
        return "financial-not-admin"
    if max_bytes is not None and (item.size_bytes or 0) > max_bytes:
        return "too_large"
    return None


