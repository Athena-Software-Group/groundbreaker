def compose_steps(opts: ComposeOptions, *, confirm=None, can_send: bool = False,
                  transport_problem: str | None = None) -> list[ComposeStep]:
    """The stepper's four steps with their state, from what the page shows (`opts` after any error; `confirm`: the
    prepared e-mail waiting for "Confirm and send" on the page). Display only: the server checks every field again."""
    errors = opts.errors or {}
    n_to = sum(1 for r in opts.recipients if r.to_checked) + len(_split(opts.to_other))
    n_cc = sum(1 for r in opts.recipients if r.cc_checked) + len(_split(opts.cc_other)) + sum(
        1 for o in opts.cc_offers if o.checked and not o.blocked)
    n_bcc = len(_split(opts.bcc_other))
    who = f"{n_to} To · {n_cc} Cc" + (f" · {n_bcc} Bcc" if n_bcc else "")
    if errors.keys() & {"to", "cc", "bcc"}:
        rec = ComposeStep(1, "recipients", "Recipients", "step-recipients", "error", who)
    elif n_to:
        rec = ComposeStep(1, "recipients", "Recipients", "step-recipients", "done", who)
    else:
        rec = ComposeStep(1, "recipients", "Recipients", "step-recipients", "todo", "choose at least one To")
    chars = f"{len(opts.body or ''):,} characters"
    if errors.keys() & {"subject", "body", "draft"}:
        letter = ComposeStep(2, "letter", "Letter", "step-letter", "error", chars)
    elif not (opts.subject or "").strip() or not (opts.body or "").strip():
        letter = ComposeStep(2, "letter", "Letter", "step-letter", "todo", "a subject and the text")
    elif opts.sender is not None and opts.sender.needs_ack:
        letter = ComposeStep(2, "letter", "Letter", "step-letter", "warn", "not signed as the sender of record")
    else:
        letter = ComposeStep(2, "letter", "Letter", "step-letter", "done", chars)
    n_att = sum(1 for a in opts.attachments if a.checked and not a.blocked_reason)
    att_text = f"{n_att} file{'s' if n_att != 1 else ''} attached"
    att = ComposeStep(3, "attachments", "Attachments", "attachments",
                      "error" if errors.keys() & {"attach", "upload", "attachment"} else "done", att_text)
    if opts.busy is not None or opts.checklist is not None:
        send = ComposeStep(4, "send", "Review & send", "mail-next", "locked",
                           "another e-mail of this letter is out" if opts.busy is not None else "an Outlook checklist is open")
    elif confirm is not None:
        send = ComposeStep(4, "send", "Review & send", "confirm", "current", "confirm the recipients, then Send")
    else:
        ready = all(s.state in ("done", "warn") for s in (rec, letter, att))
        how = ("prepare it, then send it from Outlook" if opts.manual else
               "Send now: you confirm, then it goes out" if can_send and opts.mailbox and not transport_problem else
               "prepare it for a case admin to send")
        send = ComposeStep(4, "send", "Review & send", "mail-next", "todo", how if ready else "finish the steps above",
                           ready=how)
    return [rec, letter, att, send]


def redirect_hint(db: Session, case, corr: Correspondence, authority) -> dict | None:
    """When the authority's reply redirected us (app.blocks.status: a legacy / wrong address naming another one),
    what the compose page says: the address the reply named and the one that redirected us. First the request
    this draft belongs to (when it reads "redirected"); else the authority's latest redirect from its own domain
    (mail_guidance._redirects), so a new letter that is not tied to the redirected request — an information
    request after a redirected stop order — is not addressed to the inbox they said not to use. The address
    named for this letter's purpose (freeze vs legal process: `pick_resend`) is prefilled only when the reply
    came from the authority's own domain (`sender_domain_ok`) and names an address on that same domain;
    otherwise it is only shown. None for a sent letter, no redirect, or on any failure (advice only)."""
    if corr is None or corr.status != CorrespondenceStatus.DRAFT or corr.direction != CorrespondenceDirection.OUT:
        return None
    try:
        from app.blocks import status as block_status
        from app.domain import mail_guidance

        def hint(target, sender, trusted, at, reply_id):
            if not target or "@" not in target:
                return None
            sender = (sender or "").strip().lower()
            own_domain = sender.rpartition("@")[2]
            prefill = trusted and bool(own_domain) and target.lower().rpartition("@")[2] == own_domain
            return {"to": target, "legacy": sender or None, "at": at, "reply_id": reply_id, "prefilled": prefill}

        kind = corr.kind.value
        rows = block_status.case_blocks(db, case)
        row = next((r for r in rows if r.authority.key == getattr(authority, "key", None) and (
            (corr.stop_order_id is not None and r.order is not None and r.order.id == corr.stop_order_id)
            or (r.letter is not None and r.letter.id == corr.id))), None)
        if row is not None and row.status == block_status.rules.REDIRECTED and row.deciding is not None:
            # the address for this letter's purpose (a freeze follow-up → the freeze inbox, never the subpoena one)
            d = row.deciding
            found = hint(block_status.pick_resend(d.addresses, kind) or row.resend_to, d.corr.sender,
                         d.sender_domain_ok is True, d.at, d.corr.id)
            if found is not None:
                return found
        # any other letter to this authority: their latest redirect from their own domain, for this purpose
        rd = next((r for r in mail_guidance._redirects(db, case, authority, kind) if r.trusted and r.to), None)
        if rd is None:
            return None
        return hint(rd.to, rd.away, True, rd.at, rd.reply_id)
    except Exception:  # noqa: BLE001 - a hint: the compose page works without it
        log.debug("compose: no redirect hint")
        return None


def _reply_target(db: Session, corr: Correspondence) -> tuple[str | None, int | None]:
    """The Message-ID this letter answers: its `references` letter (c<ID> / o<ID>) when Aegis mail sent it."""
    ref = str((corr.meta or {}).get("references") or "")
    target: Correspondence | None = None
    if re.fullmatch(r"c\d{1,12}", ref):
        target = db.get(Correspondence, int(ref[1:]))
    elif re.fullmatch(r"o\d{1,12}", ref):
        target = db.scalar(select(Correspondence).where(Correspondence.stop_order_id == int(ref[1:]),
                                                        Correspondence.direction == CorrespondenceDirection.OUT,
                                                        Correspondence.case_id == corr.case_id))
    if target is None or target.case_id != corr.case_id:
        return None, None
    mm = db.scalar(select(MailMessage).where(MailMessage.correspondence_id == target.id,
                                             MailMessage.direction == MailDirection.OUT,
                                             MailMessage.status == MailStatus.SENT).order_by(MailMessage.id.desc()))
    if mm is None:
        return None, None
    return (mm.internet_message_id or mm.message_id), target.id


def compose_options(db: Session, access, corr: Correspondence, authority, form: dict | None = None) -> ComposeOptions:
    from app.domain import mail_guidance, sender

    settings = _settings()
    manual = is_manual(settings)
    card = directory.channels_for(db, access, authority)
    requester = sender.requester_kind(db, access.case)
    mailbox = settings.mail_from or None
    draft_to = {a.strip().lower() for a in corr.recipients or [] if a and "@" in a}
    draft_cc = {a.strip().lower() for a in corr.cc or [] if a and "@" in a}
    recipients: list[RecipientOption] = []
    seen: set[str] = set()

    def demo_locked(address: str) -> bool:  # the demo lock: a real organisation's address is never offered
        return demo_lock_problem(access.case, [address], mailbox=mailbox if manual else None) is not None

    for e in card.emails():
        a = e.value.lower()
        if a in seen or a == (mailbox or "") or demo_locked(a):
            continue
        seen.add(a)
        le_only = e.le_only and requester not in playbook.OFFICIAL
        recipients.append(RecipientOption(
            address=e.value, label=e.label or e.source.replace("_", " "), role_default=e.role_default,
            verified=e.verified, source=e.source, scope=e.scope,
            to_checked=not le_only and (a in draft_to or (e.verified and e.role_default == "to" and a not in draft_cc)),
            cc_checked=not le_only and a in draft_cc, le_only=le_only))
    if manual and mailbox:  # a person sends it: the case mailbox may be copied (never addressed)
        seen.add(mailbox)
        recipients.append(RecipientOption(address=mailbox, label="the case mailbox (AEGIS_MAIL_FROM)", role_default="cc",
                                          verified=True, source="case_mailbox", scope="global",
                                          cc_checked=mailbox in draft_cc))
    others_to = [a for a in corr.recipients or [] if a and a.strip().lower() not in seen and not demo_locked(a)]
    others_cc = [a for a in corr.cc or [] if a and a.strip().lower() not in seen and not demo_locked(a)]
    profile = sender.get_profile(db, access.case)
    max_bytes = max_bytes_for(settings)
    attachments = [AttachmentOption(ref="letter", kind="letter_docx", title=f"Letter #{corr.id} as .docx",
                                    checked=True)]
    auth_ids = [int(i) for i in (profile.authority_evidence_ids or [])] if profile is not None else []
    visible = {e.id: e for e in ev.visible_items(access)}
    mask = ev.ref_mask(access)
    exempt = frozenset(auth_ids)
    for eid in auth_ids:
        item = visible.get(eid)
        if item is None:
            continue
        reason = static_block_reason(access, item, max_bytes=max_bytes) \
            or authority_block_reason(db, item, authority, exempt=exempt)
        attachments.append(_att_option(item, "authority_doc", f"authority:{eid}", mask, reason, checked=reason is None))
    uploaded = uploaded_ids(corr)
    # files uploaded for this letter first (newest first), then the rest of the case's evidence
    for item in sorted(visible.values(), key=lambda e: (e.id not in uploaded, -e.id if e.id in uploaded else e.id)):
        if item.id in auth_ids:
            continue
        reason = static_block_reason(access, item, max_bytes=max_bytes) \
            or authority_block_reason(db, item, authority, exempt=exempt)
        opt = _att_option(item, "evidence", f"evidence:{item.id}", mask, reason)
        opt.uploaded = item.id in uploaded
        attachments.append(opt)
    in_reply_to, reply_corr = _reply_target(db, corr)
    opts = ComposeOptions(
        corr=corr, authority=authority, card=card, recipients=recipients, subject=(corr.subject or "")[:SUBJECT_MAX],
        tag=tracking_tag(access.case, corr), attachments=attachments, draft_hash=draft_hash(corr),
        in_reply_to=in_reply_to, in_reply_to_corr=reply_corr, mailbox=mailbox,
        transport=settings.aegis_mail_transport, to_other=", ".join(others_to), cc_other=", ".join(others_cc),
        max_bytes=max_bytes, sender=sender_check(db, access.case, corr, settings), manual=manual,
        body=corr.body_markdown or "")
    try:
        opts.guidance = mail_guidance.for_authority(db, access, authority, corr, card=card, settings=settings)
    except Exception:  # noqa: BLE001 - guidance is advice: the compose page works without it
        opts.guidance = None
    if manual and opts.guidance is not None and form is None:
        opts.subject = opts.guidance.subject_body[:SUBJECT_MAX]  # the standard pattern; the tag follows it
    top = opts.guidance.to[0].address if opts.guidance is not None and opts.guidance.to else None
    if form is None and top is not None and top.lower() not in draft_cc and top.lower() != (mailbox or "") \
            and not others_to:  # an address a person typed on the letter itself stays its To
        # the To by default is the one "How to email" suggests (its rank 1), not another address on file: its row
        # ticked, or typed in when it is no row of the table (confirmed one by one before sending, like any typed one)
        listed = any(r.address.lower() == top.lower() for r in opts.recipients)
        for r in opts.recipients:
            r.to_checked = not r.le_only and r.address.lower() == top.lower()
        opts.to_other = "" if listed else top
    busy = letter_in_flight(db, corr) if corr.id is not None else None
    if busy is not None:
        opts.busy, opts.busy_text = busy, letter_busy_text(corr, busy)
    opts.redirect = redirect_hint(db, access.case, corr, authority)
    if opts.redirect is not None and requester not in playbook.OFFICIAL \
            and opts.redirect["to"].lower() in card.le_only_addresses():
        opts.redirect = {**opts.redirect, "prefilled": False, "le_only": True}  # LE only: never typed in for us
    if opts.redirect is not None and demo_locked(opts.redirect["to"]):
        opts.redirect = {**opts.redirect, "prefilled": False}  # the demo lock: never typed in for a demo case
    if opts.redirect is not None and form is None and opts.redirect["prefilled"]:
        # their reply named the address for this request: typed in (confirmed one by one before sending), and the
        # address that redirected us is not pre-ticked
        legacy = (opts.redirect.get("legacy") or "").lower()
        for r in opts.recipients:
            if r.address.lower() == legacy:
                r.to_checked = False
        others = [a.strip() for a in opts.to_other.split(",") if a.strip() and a.strip().lower() != legacy]
        if opts.redirect["to"].lower() not in {a.lower() for a in others} | {
                r.address.lower() for r in opts.recipients if r.to_checked}:
            others.insert(0, opts.redirect["to"])
        opts.to_other = ", ".join(others)
    saved = saved_draft(corr) if form is None else None
    chosen = form if form is not None else saved
    if chosen is not None:  # re-render after an error, or the fields the editor saved: keep what the member chose
        if form is not None or "to" in chosen or "cc" in chosen:  # (the letter page's Edit draft drops them)
            le_only = {r.address.lower() for r in opts.recipients if r.le_only}
            chosen_to = {str(a).lower() for a in chosen.get("to") or []} - le_only
            chosen_cc = {str(a).lower() for a in chosen.get("cc") or []} - le_only
            for r in opts.recipients:
                r.to_checked, r.cc_checked = r.address.lower() in chosen_to, r.address.lower() in chosen_cc
            offered = {r.address.lower() for r in opts.recipients}

            def typed(key: str, other: str) -> str:  # chosen addresses that are not a row of the table: typed in
                extra = [str(a) for a in chosen.get(key) or [] if str(a).lower() not in offered]
                return ", ".join(x for x in [str(chosen.get(other) or "").strip(), *extra] if x)

            opts.to_other, opts.cc_other = typed("to", "to_other"), typed("cc", "cc_other")
        opts.bcc_other = chosen.get("bcc_other") or ""
        if form is not None or "subject" in chosen:
            opts.subject = (chosen.get("subject") or "")[:SUBJECT_MAX]
        refs = set(chosen.get("attach") or [])
        for a in opts.attachments:
            a.checked = a.ref in refs and not a.blocked_reason
        if form is not None and "body_markdown" in form:
            opts.body = str(form.get("body_markdown") or "")
    if saved is not None:
        opts.saved_at = saved.get("saved_at")
    opts.cc_offers, opts.cc_note = cc_offers(db, access, settings, le_only=card.le_only_addresses()
                                             if requester not in playbook.OFFICIAL else frozenset())
    picked = (set(_split(form.get("cc_add"))) if form is not None and form.get("cc_offered") else
              set(saved.get("cc_add") or []) if saved is not None and "cc_add" in saved else None)
    for o in opts.cc_offers:  # the member's choice for this letter (meta.mail_draft), else the default
        o.checked = not o.blocked and (o.default if picked is None else o.key in picked)
    if corr.id is not None:
        opts.checklist = None if manual else open_checklist(db, corr)
        if opts.checklist is not None:
            opts.checklist_text = checklist_text(opts.checklist)
        opts.waiting = [r for r in db.scalars(select(MailMessage).where(
            _same_letter(corr), MailMessage.direction == MailDirection.OUT, MailMessage.status == MailStatus.PREPARED,
            MailMessage.expires_at > _now()).order_by(MailMessage.id)).all()
            if opts.checklist is None or r.id != opts.checklist.id]  # an expired one is not waiting
    return opts


