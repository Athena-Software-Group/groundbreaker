def _dev_allowed(settings) -> set[str] | None:
    """The domains local-mode Graph sending is limited to (AEGIS_MAIL_DEV_ALLOWED_DOMAINS), or None: no limit."""
    from app.core.config import get_settings

    if get_settings().is_local and settings.aegis_mail_transport == "graph" and not getattr(
            settings, "aegis_mail_live_sending", False):
        return set(settings.dev_allowed_domains)
    return None


def cc_offers(db: Session, access, settings=None, *, le_only: set[str] | frozenset = frozenset()
              ) -> tuple[list[CcOffer], str | None]:
    """The compose page's Cc boxes: the sender of record's contact e-mail (ticked by default) and the signed-in
    member's own address when it is a real mailbox (not ticked), with the note shown instead of the sender's box when
    the sender's address is the case mailbox itself (it is never a recipient: its Sent Items keeps the copy)."""
    from app.domain import sender as sender_mod

    settings = settings if settings is not None else _settings()
    mailbox = (settings.mail_from or "").strip().lower()
    allowed = _dev_allowed(settings)
    profile = sender_mod.get_profile(db, access.case)
    out: list[CcOffer] = []
    note = None

    def blocked(a: str) -> str | None:
        if a.lower() in le_only:
            return "reserved for law enforcement by the provider"
        if allowed is not None and not _domain_allowed(a, allowed):
            return "local mode: not in AEGIS_MAIL_DEV_ALLOWED_DOMAINS"
        if demo_lock_problem(access.case, [a]):
            return "demo case: reserved demo addresses only"
        return None

    if profile is not None:
        contact = (profile.contact_email or "").strip().lower() or mailbox
        if contact and contact == mailbox:
            note = (f"The sender of record's e-mail is the case mailbox ({mailbox}): no Cc needed, its Sent Items "
                    "already keeps a copy.")
        elif contact:
            try:
                a = directory.validate_address(contact)
            except directory.DirectoryError:
                a = None
            if a is not None:
                why = blocked(a)
                out.append(CcOffer("sender", a, "Cc the sender of record", default=why is None, blocked=why))
    user = getattr(access, "user", None)
    me = routable_address(getattr(user, "email", None))
    if me is not None and me.lower() != mailbox and me.lower() not in {o.address.lower() for o in out}:
        out.append(CcOffer("me", me, "Cc me", blocked=blocked(me)))
    for o in out:
        o.checked = o.default
    return out, note


def cc_offer_addresses(db: Session, access, form: dict, settings=None, *, le_only=frozenset()) -> list[str]:
    """The addresses the form's Cc boxes add (`cc_add`), only when the form carries them (`cc_offered`: the compose
    page) and only those offered now (never an address taken from the form)."""
    if not form.get("cc_offered"):
        return []
    picked = set(_split(form.get("cc_add")))
    offers, _note = cc_offers(db, access, settings, le_only=le_only)
    return [o.address for o in offers if o.key in picked and not o.blocked]


def _fold_cc_offers(db: Session, access, form: dict) -> None:
    """A `renew_form` for the editor: the offered Cc addresses it copies leave its Cc and tick their boxes."""
    offers, _note = cc_offers(db, access)
    by_addr = {o.address.lower(): o.key for o in offers}
    form["cc_add"] = [by_addr[a.lower()] for a in form["cc"] if a.lower() in by_addr]
    form["cc"] = [a for a in form["cc"] if a.lower() not in by_addr]
    form["cc_offered"] = "1"


