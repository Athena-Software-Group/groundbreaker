# --------------------------------------------------------------------------- tags, hashes, bodies
def tracking_tag(case, corr) -> str:
    return f"[Aegis {case.reference} #{corr.id}]"


def strip_tag(case, corr, subject: str) -> str:
    """The subject without this letter's own tracking tag (wherever the member typed or pasted it)."""
    tag = tracking_tag(case, corr)
    if tag not in (subject or ""):
        return (subject or "").strip()
    return re.sub(r" {2,}", " ", (subject or "").replace(tag, " ")).strip()  # control characters stay (refused later)


# Typographic punctuation in a Subject forces RFC 2047 encoded words, which Python <= 3.13 folds badly
# (a stray space, or an encoded word over 75 characters). Plain ASCII headers fold and unfold exactly.
_ASCII_PUNCT = str.maketrans({"–": "-", "—": "-", "‒": "-", "−": "-", "‘": "'", "’": "'",
                              "“": '"', "”": '"', " ": " ", "…": "..."})


def ascii_header(text: str) -> str:
    """`text` with typographic dashes, quotes, ellipses and no-break spaces as ASCII (other characters,
    e.g. accented letters a member typed, are kept and sent as encoded words)."""
    return (text or "").translate(_ASCII_PUNCT)


def tagged_subject(case, corr, subject: str, *, suffix: bool = False) -> str:
    """Tag first (Aegis sends it), or at the end (manual mode: the guidance patterns end with it). The
    result is what goes in the Subject header, so typographic punctuation is made ASCII (`ascii_header`)."""
    body = ascii_header(strip_tag(case, corr, subject))
    return (f"{body} {tracking_tag(case, corr)}" if suffix else f"{tracking_tag(case, corr)} {body}").strip()


def draft_hash(corr: Correspondence) -> str:
    """What the preview was built from: subject, body, recipients and cc of the draft."""
    material = "\x1f".join([corr.subject or "", corr.body_markdown or "", "\x1e".join(corr.recipients or []),
                            "\x1e".join(corr.cc or [])])
    return hashlib.sha256(material.encode("utf-8")).hexdigest()


def outbound_markdown(body: str | None) -> str:
    """The letter as it goes out: without the internal provenance footer (`_FOOTER_RE`), wherever it sits; the text
    around it closes up to one blank line."""
    text = (body or "").replace("\r\n", "\n").rstrip()
    text = _FOOTER_RE.sub("", text)
    return text.rstrip() + "\n"


_LINK_RE = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")


def markdown_to_text(md: str | None) -> str:
    """Plain text of a letter: headings without '###', bullets kept, emphasis markers and backticks
    removed, backslash escapes rendered as the plain character."""
    text = so._ESCAPED.sub(lambda m: so._SHIELD[m.group(1)], outbound_markdown(md))
    out = []
    for line in text.split("\n"):
        s = line.rstrip()
        if re.fullmatch(r"\s*(\* \* \*|---+)\s*", s):
            out.append("")
            continue
        s = re.sub(r"^#{1,6} ", "", s)
        s = s.replace("**", "").replace("`", "")
        s = re.sub(r"(?<![\w*])\*(?=\S)([^*\n]+?)(?<=\S)\*(?![\w*])", r"\1", s)
        s = _LINK_RE.sub(lambda m: f"{m.group(1)} <{m.group(2)}>", s)
        out.append(so._unshield(s))
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip() + "\n"


