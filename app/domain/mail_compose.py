def is_correspondence_item(item: EvidenceItem, db: Session | None = None) -> bool:
    """Correspondence with an authority filed as evidence: an e-mail Aegis sent (.eml), one it received
    (.eml or an extracted attachment) — see `is_mail_item` — or anything in the Stop orders &
    correspondence folder."""
    return item.folder == EvidenceFolder.STOP_ORDERS_CORRESPONDENCE or is_mail_item(item, db)


def correspondence_origins(db: Session, item: EvidenceItem) -> set[int]:
    """The correspondence rows an evidence item belongs to: rows that file or link it
    (evidence_item_id / meta.evidence_ids), the letter of the outbound e-mail it is the .eml of, and
    the entry the inbound e-mail it came with was filed as (meta.mail_message_id)."""
    out: set[int] = set()
    for c in db.scalars(select(Correspondence).where(Correspondence.case_id == item.case_id)).all():
        ids = {int(i) for i in (c.meta or {}).get("evidence_ids") or [] if str(i).isdigit()}
        if c.evidence_item_id == item.id or item.id in ids:
            out.add(c.id)
    mids = set()
    raw = (item.meta or {}).get("mail_message_id")
    if str(raw or "").isdigit():
        mids.add(int(raw))
    rows = db.scalars(select(MailMessage).where((MailMessage.eml_evidence_id == item.id)
                                                | (MailMessage.id.in_(mids or {-1})))).all()
    out |= {m.correspondence_id for m in rows if m.correspondence_id and m.case_id == item.case_id}
    return out


def authority_block_reason(db: Session, item: EvidenceItem, authority, *, exempt: set[int] | frozenset = frozenset()
                           ) -> str | None:
    """"other_authority" when a correspondence item (`is_correspondence_item`) would go to an
    authority it did not come from: every correspondence row it belongs to must be one of
    `authority`'s; an item whose origin cannot be traced is refused too. The sender profile's own
    authority documents (`exempt`) are never correspondence of one authority — unless they are an
    e-mail or a file from one (`is_mail_item`), which sender.authority_doc_problem refuses to save
    but an older profile may still list."""
    if not is_correspondence_item(item, db) or (item.id in exempt and not is_mail_item(item, db)):
        return None
    origins = correspondence_origins(db, item)
    own = {c.id for c in getattr(authority, "correspondence", None) or [] if c.id is not None}
    return None if origins and origins <= own else "other_authority"


_AUTH_MENTION = re.compile(r"(?i)\b(letters? of authori[sz]ation|letters? of authority|authori[sz]ation letter|"
                           r"power of attorney|written authori[sz]ation|mandate letter)\b")
_ATTACH_CUE = re.compile(r"(?i)\b(attached|attach|attaching|enclosed|enclose|enclosing|herewith)\b")


def authorisation_warning(db: Session, case, corr: Correspondence | None, manifest: list[dict]) -> str | None:
    """A letter that says its authority instrument (Letter of Authorisation …) is attached, while
    the e-mail carries no authority document: the preview warns (Send is not blocked)."""
    from app.domain import sender as sender_mod

    if corr is None:
        return None
    text = markdown_to_text(corr.body_markdown)
    profile = sender_mod.get_profile(db, case)
    instrument = (getattr(profile, "instrument", None) or "").strip()
    mentioned = bool(_AUTH_MENTION.search(text)) or (len(instrument) >= 6 and instrument.lower() in text.lower())
    if not mentioned or not _ATTACH_CUE.search(text):
        return None
    if any(m.get("kind") == "authority_doc" for m in manifest or []):
        return None
    for m in manifest or []:
        if m.get("kind") == "evidence" and m.get("evidence_id"):
            item = db.get(EvidenceItem, int(m["evidence_id"]))
            if item is not None and re.search(r"(?i)authori[sz]|attorney|mandate|instrument", item.title or ""):
                return None
    what = instrument or "Letter of Authorisation"
    return (f"The letter says the {what} is attached, but this e-mail carries no authority document. Add it "
            "(the sender profile's authority documents are offered pre-ticked) or change the letter before "
            "sending.")


def _ext(item: EvidenceItem) -> str:
    if item.storage == EvidenceStorage.INLINE:
        return "txt"
    name = str((item.meta or {}).get("original_filename") or "")
    if "." in name:
        ext = re.sub(r"[^A-Za-z0-9]", "", name.rsplit(".", 1)[1])[:10].lower()
        if ext:
            return ext
    import mimetypes

    guess = mimetypes.guess_extension(item.mime or "") or ".bin"
    return guess.lstrip(".")[:10] or "bin"


def _mime_of(item: EvidenceItem) -> str:
    if item.storage == EvidenceStorage.INLINE:
        return "text/plain"
    m = (item.mime or "").split(";")[0].strip().lower()
    return m if re.fullmatch(r"[a-z0-9.+-]+/[a-z0-9.+-]+", m) else "application/octet-stream"


def safe_filename(name: str, taken: set[str]) -> str:
    """[A-Za-z0-9._-] only, at most 100 characters, unique within the message."""
    base = re.sub(r"[^A-Za-z0-9._-]+", "-", name).strip(".-") or "attachment"
    base = base[:100]
    out, n = base, 1
    while out.lower() in taken:
        n += 1
        stem, dot, ext = base.rpartition(".")
        stem, ext = (stem, ext) if dot else (base, "")
        suffix = f"-{n}"
        out = f"{stem[:100 - len(suffix) - len(ext) - 1]}{suffix}" + (f".{ext}" if ext else "")
    taken.add(out.lower())
    return out


def mark_mail_safe(db: Session, access, item: EvidenceItem, *, safe: bool = True) -> EvidenceItem:
    """A case admin marks an e-mail-received evidence item safe to attach (or withdraws it). Never
    for a dangerous, TLP-blocked or integrity-failed item. The caller audits."""
    if not access.can("send_email"):
        raise ComposeError("only case admins may mark a received file safe to attach", "attach")
    if item.case_id != access.case.id or not is_inbound(item):
        raise ComposeError("only a file received by e-mail needs this", "attach")
    if safe and is_received_email(item):
        raise ComposeError("a received e-mail itself is never attached: mark the files extracted from it safe "
                           "instead", "attach")
    if safe and (is_dangerous(item) or tlp_blocked(item) or ev.integrity_status(item) in ("mismatch", "missing")):
        raise ComposeError("this file can never be attached", "attach")
    meta = dict(item.meta or {})
    if safe:
        meta["mail_safe"] = {"by": access.user.id, "at": _now().isoformat()}
    else:
        meta.pop("mail_safe", None)
    item.meta = meta
    db.commit()
    return item


