def prepare(db: Session, access, corr: Correspondence, authority, form: dict) -> MailMessage:
    """Validate the compose form, build the exact MIME, store it in the vault and create the
    `prepared` row (expires after 30 minutes). Raises ComposeError (field-level message)."""
    from app.core.config import get_settings

    _check_draft(access, corr)
    if not access.can("prepare_email"):
        raise ComposeError("your role cannot prepare e-mails", "form")
    refuse_pointless(db, corr)
    if (form.get("draft_hash") or "") != draft_hash(corr):
        raise ComposeError("the draft changed while you were composing; review it and prepare again", "draft")
    busy = letter_in_flight(db, corr)
    if busy is not None:
        raise ComposeError(letter_busy_text(corr, busy), "letter")
    refuse_open_checklist(db, corr)
    settings = _settings()
    manual = is_manual(settings)
    mail_from = settings.mail_from
    if (not mail_from or "@" not in mail_from) and not manual:
        raise ComposeError("AEGIS_MAIL_FROM is not set: Aegis has no mailbox to send from", "mailbox")
    mail_from = mail_from if mail_from and "@" in mail_from else ""
    _vault()
    opts = compose_options(db, access, corr, authority)
    to = _addresses(_split(form.get("to")) + _split(form.get("to_other")), "to")
    # the Cc boxes (the sender of record, me): our own addresses, offered by the server, never confirmed one by one
    own_cc = [o.address for o in opts.cc_offers if not o.blocked and form.get("cc_offered")
              and o.key in set(_split(form.get("cc_add")))]
    cc = [a for a in _addresses(_split(form.get("cc")) + _split(form.get("cc_other")) + own_cc, "cc")
          if a.lower() not in {x.lower() for x in to}]
    bcc = [a for a in _addresses(_split(form.get("bcc")) + _split(form.get("bcc_other")), "bcc")
           if a.lower() not in {x.lower() for x in to + cc}]
    if not to:
        raise ComposeError("choose at least one To recipient", "to")
    if len(to) > MAX_TO:
        raise ComposeError(f"at most {MAX_TO} To recipients", "to")
    if len(cc) > MAX_CC:
        raise ComposeError(f"at most {MAX_CC} Cc recipients", "cc")
    if len(bcc) > MAX_BCC:
        raise ComposeError(f"at most {MAX_BCC} Bcc recipients", "bcc")
    if len(to) + len(cc) + len(bcc) > MAX_UNIQUE:
        raise ComposeError(f"at most {MAX_UNIQUE} recipients in all", "to")
    from app.domain import sender

    if sender.requester_kind(db, access.case) not in playbook.OFFICIAL:
        blocked = [a for a in to + cc + bcc if a.lower() in opts.card.le_only_addresses()]
        if blocked:
            raise ComposeError(f"{playbook.LE_ONLY_REASON}: {', '.join(blocked)} is reserved for law enforcement by "
                               f"{getattr(authority, 'name', 'the provider')}; brief the case officer with the pack "
                               "instead (an LE cover letter to the case's LE authority)", "to")
    if mail_from and any(a.lower() == mail_from.lower() for a in (to if manual else to + cc + bcc)):
        field_name = "to" if manual or any(a.lower() == mail_from.lower() for a in to) else \
            "cc" if any(a.lower() == mail_from.lower() for a in cc) else "bcc"
        raise ComposeError("the case mailbox cannot be a recipient of its own message" + (
            " (copy it as Cc instead)" if manual else
            f" (remove {mail_from} from {field_name.capitalize()}: Aegis sends from it and its Sent Items keeps a copy)"),
            field_name)
    if get_settings().is_local and settings.aegis_mail_transport == "graph" and not getattr(
            settings, "aegis_mail_live_sending", False):  # AEGIS_MAIL_LIVE_SENDING=1: the owner went live
        allowed = settings.dev_allowed_domains
        bad = [a for a in to + cc + bcc if not _domain_allowed(a, allowed)]
        if bad:
            raise ComposeError("local mode: real Microsoft 365 sending is limited to the domains in "
                               "AEGIS_MAIL_DEV_ALLOWED_DOMAINS", "to")
    demo = demo_lock_problem(access.case, to + cc + bcc, mailbox=mail_from if manual else None)
    if demo:  # the demo lock: whatever the transport and AEGIS_MAIL_LIVE_SENDING say
        raise ComposeError(demo, "to" if demo_lock_problem(access.case, to) else
                           "cc" if demo_lock_problem(access.case, cc, mailbox=mail_from if manual else None) else "bcc")
    subject = strip_tag(access.case, corr, (form.get("subject") or "").strip())
    _no_ctl(subject, "subject")
    if not subject:
        raise ComposeError("a subject is required", "subject")
    if len(subject) > SUBJECT_MAX:
        raise ComposeError(f"the subject is longer than {SUBJECT_MAX} characters", "subject")
    subject = tagged_subject(access.case, corr, subject, suffix=manual)
    max_bytes = max_bytes_for(settings)

    # attachments: only offered, unblocked options; bytes read once and verified
    by_ref = {a.ref: a for a in opts.attachments}
    refs = list(dict.fromkeys(_split(form.get("attach"))))
    ref_name = re.sub(r"[^A-Za-z0-9._-]+", "-", access.case.reference)[:40]
    taken: set[str] = set()
    files: list[tuple[str, str, bytes]] = []
    manifest: list[dict] = []
    for ref in refs:
        opt = by_ref.get(ref)
        if opt is None:
            raise LookupError("attachment not found")  # another case's evidence, or an unknown id: 404
        if opt.blocked_reason:
            raise ComposeError(f"{opt.title[:80]} cannot be attached: {opt.blocked_text}", "attach")
        if opt.kind == "letter_docx":
            data = so.markdown_to_docx_bytes(corr.subject or "Letter", outbound_markdown(corr.body_markdown),
                                             access.case.reference, final=True)
            name, mime, eid = safe_filename(f"{ref_name}_letter-{corr.id}.docx", taken), DOCX_MIME, None
        else:
            item = db.get(EvidenceItem, opt.evidence_id)
            if item is None or item.case_id != access.case.id or not ev.can_see(access, item):
                raise LookupError("attachment not found")
            reason = static_block_reason(access, item, max_bytes=max_bytes)
            if reason is None:
                reason = authority_block_reason(db, item, authority, exempt=_profile_doc_ids(db, access.case))
            if reason:
                raise ComposeError(f"{opt.title[:80]} cannot be attached: {BLOCK_TEXT[reason]}", "attach")
            try:
                data = ev.read_verified(item)
            except ev.IntegrityError:
                raise ComposeError(f"{opt.title[:80]} cannot be attached: {BLOCK_TEXT['integrity']}", "attach") from None
            except (OSError, ev.EvidenceError, KeyError):
                raise ComposeError(f"{opt.title[:80]} cannot be attached: {BLOCK_TEXT['unreadable']}", "attach") from None
            kind_slug = "authority" if opt.kind == "authority_doc" else "evidence"
            name = safe_filename(f"{ref_name}_{kind_slug}-{item.id}.{_ext(item)}", taken)
            mime, eid = _mime_of(item), item.id
        files.append((name, mime, data))
        manifest.append({"filename": name, "mime": mime, "size": len(data), "sha256": hashlib.sha256(data).hexdigest(),
                         "evidence_id": eid, "kind": opt.kind, "blocked_reason": None})

    now = _now()
    # manual: no Message-ID in the draft (the sending server sets it); the row keeps an empty one
    message_id = "" if manual else new_message_id(access.case, corr, settings.mail_domain)
    in_reply_to, reply_corr = opts.in_reply_to, opts.in_reply_to_corr
    raw, _ = build_mime(
        from_name=settings.from_name, mail_from=mail_from, to=to, cc=cc, subject=subject,
        text_body=markdown_to_text(corr.body_markdown), html_body=markdown_to_html(corr.body_markdown, subject),
        attachments=files, message_id=message_id, in_reply_to=in_reply_to, date=now, unsent=manual, bcc=bcc)
    limit = max_bytes
    if len(raw) > limit:
        raise ComposeError(f"This e-mail would be {len(raw) / 1e6:.1f} MB; Aegis {'drafts' if manual else 'sends'} up "
                           f"to {limit / 1e6:.1f} MB. Remove attachments or submit large files through the recipient's "
                           "portal.", "attach")
    rel = _write_pending(access.case.id, raw)
    verified = opts.card.verified_addresses()
    check = opts.sender or sender_check(db, access.case, corr, settings)
    mm = MailMessage(
        case_id=access.case.id, correspondence_id=corr.id, letter_key=letter_key(corr), direction=MailDirection.OUT,
        status=MailStatus.PREPARED,
        transport=settings.aegis_mail_transport, mailbox=mail_from, prepare_token=secrets.token_urlsafe(32),
        message_id=message_id, in_reply_to=in_reply_to, references=in_reply_to, subject=subject[:512],
        from_addr=mail_from, to_addrs=to, cc_addrs=cc, mime_sha256=hashlib.sha256(raw).hexdigest(),
        mime_size=len(raw), mime_path=rel, attachments=manifest,
        confirmations={"unverified": [a for a in to + cc + bcc
                                      if a.lower() not in verified and a.lower() != mail_from.lower()
                                      and not (a in cc and a.lower() in {x.lower() for x in own_cc})],
                       "attachments": [m["evidence_id"] for m in manifest if m["kind"] == "evidence"]},
        prepared_at=now, expires_at=now + (MANUAL_TTL if manual else PREPARE_TTL), created_by=access.user.id, attempts=0,
        match={},
        meta={"draft_hash": draft_hash(corr), "in_reply_to_corr": reply_corr, "authority_key": authority.key,
              "sender_problem": check.problem, **({"bcc": bcc} if bcc else {}),
              "history": [{"status": "prepared", "at": now.isoformat(), "by": access.user.id}]})
    db.add(mm)
    try:
        db.commit()
    except Exception:
        db.rollback()
        delete_pending(mm)
        raise
    if not access.can("send_email"):
        _announce(db, access.case, corr, mm, manual=manual)
    return mm


def _announce(db: Session, case, corr: Correspondence, mm: MailMessage, *, manual: bool = False) -> None:
    """Tell the case admins (the only ones who can press Send, or record a manual send) that a
    prepared e-mail is waiting."""
    from app.core import events

    if manual:
        title = f"{case.reference}: e-mail for letter #{corr.id} ready to send from Outlook"
        body = ("An investigator prepared an e-mail from a draft letter. A case admin sends it from the investigations "
                "mailbox (the checklist has every field, the attachments and an Outlook draft) and records it as sent.")
    else:
        title = f"{case.reference}: e-mail for letter #{corr.id} waiting for Send"
        body = ("An investigator prepared an e-mail from a draft letter. A case admin checks the preview and "
                f"presses Send before it expires ({int(PREPARE_TTL.total_seconds() // 60)} minutes), or "
                "prepares it again from the preview.")
    try:
        events.emit(db, case, events.MAIL_PREPARED, severity="info", title=title, body=body,
                    link=f"/cases/{case.id}/mail/messages/{mm.id}",
                    payload={"mail_message_id": mm.id, "correspondence_id": corr.id})
    except Exception:  # noqa: BLE001 - the prepared message stands even if the notice fails
        db.rollback()


RENEWABLE = (MailStatus.EXPIRED, MailStatus.FAILED, MailStatus.CANCELLED)


def renew_form(mm: MailMessage, case, corr: Correspondence) -> dict:
    """The compose form that prepares `mm` again unchanged (recipients, subject, attachments)."""
    subject = strip_tag(case, corr, mm.subject or "")
    refs = []
    for m in mm.attachments or []:
        if m.get("kind") == "letter_docx":
            refs.append("letter")
        elif m.get("evidence_id") and m.get("kind") in ("authority_doc", "evidence"):
            refs.append(f"{'authority' if m['kind'] == 'authority_doc' else 'evidence'}:{int(m['evidence_id'])}")
    return {"draft_hash": draft_hash(corr), "to": list(mm.to_addrs or []), "cc": list(mm.cc_addrs or []),
            "to_other": "", "cc_other": "", "bcc_other": ", ".join(bcc_of(mm)), "subject": subject, "attach": refs}


def bcc_of(mm: MailMessage) -> list[str]:
    """The Bcc addresses of an outbound e-mail (meta.bcc: never a header of a message Aegis sends)."""
    return [str(a) for a in (mm.meta or {}).get("bcc") or [] if a]


def renew(db: Session, access, mm: MailMessage, corr: Correspondence, authority) -> MailMessage:
    """Prepare an expired (also failed or cancelled) e-mail again: a new preview with the same
    recipients, subject and attachments, every check of `prepare` run again. Refused when the draft
    changed since (the member prepares from the letter instead)."""
    if mm.case_id != access.case.id or mm.direction != MailDirection.OUT or mm.correspondence_id != corr.id:
        raise LookupError("message not found")
    now = _now()
    expires = mm.expires_at if mm.expires_at is None or mm.expires_at.tzinfo else mm.expires_at.replace(tzinfo=UTC)
    if mm.status == MailStatus.PREPARED and expires is not None and now >= expires:
        path = retire_prepared(db, mm, by=None, status=MailStatus.EXPIRED)  # compare-and-swap (a Send may claim it)
        db.commit()
        if path is None:
            db.refresh(mm)
        unlink_pending(path)
    if mm.status not in RENEWABLE:
        raise ComposeError(f"this e-mail is {mm.status.value}; only an expired, failed or cancelled e-mail is "
                           "prepared again", "form")
    refuse_open_checklist(db, corr)  # an expired checklist itself, or another one of the letter
    if (mm.meta or {}).get("draft_hash") != draft_hash(corr):
        raise ComposeError("the draft changed since this e-mail was prepared; prepare it from the letter", "draft")
    form = renew_form(mm, access.case, corr)
    if mm.transport == "manual" and not is_manual():
        _drop_mailbox(form)  # a retired checklist may copy the case mailbox; Aegis now sends from it
    _fold_cc_offers(db, access, form)  # the sender-of-record / me boxes stay boxes, not typed Cc to confirm
    return prepare(db, access, corr, authority, form)

