RESERVED_DOMAINS = ("local", "localhost", "localdomain", "invalid", "test", "example", "internal", "lan",
                    "home.arpa", "example.com", "example.org", "example.net")


def routable_address(address: str | None) -> str | None:
    """The address, validated, when it is a real routable mailbox (not *@local, a reserved or example domain)."""
    try:
        a = directory.validate_address(str(address or ""))
    except directory.DirectoryError:
        return None
    d = a.rpartition("@")[2].lower()
    return None if any(d == r or d.endswith("." + r) for r in RESERVED_DOMAINS) else a


@dataclass
class CcOffer:
    key: str  # sender | me (form value of `cc_add`)
    address: str
    label: str
    default: bool = False
    checked: bool = False
    blocked: str | None = None  # why it cannot be copied here (the box is disabled)


