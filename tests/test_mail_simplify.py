def test_usd_short():
    assert [_usd_short(v) for v in (None, 0, 950, 1000, 63_849, 999_949, 1_234_567)] == \
        ["—", "$0", "$950", "$1k", "$63.8k", "$999.9k", "$1.2M"]


def test_owners_table_money_is_compact_and_the_next_step_has_the_width(db, case, run, client_for):  # noqa: F811
    page = client_for("investigator", case=case).get(f"/cases/{case.id}/recovery-plan").text
    panel = page.split('id="owners"')[1].split('id="owner-lookups"')[0]
    assert '<th class="own-next">Next step</th>' in panel and '<th class="own-money"' in panel
    cells = re.findall(r'<td class="own-money" title="([^"]*)"><b>([^<]*)</b>(?: <span class="own-basis">([^<]*)'
                       r'</span>)?</td>', panel)
    assert cells, "no Money cell"
    for title, fig, tag in cells:
        assert fig == "—" or re.fullmatch(r"\$\d{1,3}(\.\d)?[kM]?", fig), fig  # "$63.8k", never "$63,849"
        assert tag in ("traced", "on-chain", "frozen", "float", "up to", "swept", "conflict", "router", "passed",
                       "not read"), tag
        assert len(title) > len(tag)  # the full basis in the tooltip
    assert '<details class="own-details"><summary class="bk-small">details' in panel
    assert re.search(r'<td class="own-next"><a class="btn small" href="[^"]+">[^<]+</a>', panel)
