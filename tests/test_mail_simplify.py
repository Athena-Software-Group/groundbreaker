def test_cc_me_only_for_a_real_mailbox_and_never_ticked_by_default(db, case, run, client_for, mail,  # noqa: F811
                                                                    monkeypatch):
    # a live (non-demo) case (the demo lock keeps a demo case's e-mail on reserved demo domains: tests/test_demo_lock.py)
    monkeypatch.setattr(type(case), "is_demo", property(lambda self: False))
    at = "@"  # addresses built at run time: the PII scan reads only literal addresses on reserved domains
    for bad in ("me@local", "admin@tests.example", f"x{at}box.test", f"y{at}corp.local", "z@example.com", "q@localhost"):
        assert compose.routable_address(bad) is None, bad
    real = "athena-desk-demo" + ".io"  # a routable-looking domain (not a reserved test name)
    assert compose.routable_address(f"Lead{at}Athena-Desk-Demo.io") == f"Lead{at}{real}"
    corr = _draft(db, case, run)
    url = f"/cases/{case.id}/authorities/correspondence/{corr.id}/email"
    assert 'id="mail-cc-me"' not in client_for("admin", case=case).get(url).text  # admin@tests.example
    me = f"case.lead{at}{real}"
    adm = client_for("admin", case=case, email=me)
    page = adm.get(url).text
    assert 'id="mail-cc-me"' in page and not re.search(r'id="mail-cc-me"\s+checked', page)
    mm = _prepared(db, _compose(adm, case, corr, cc_offered="1", cc_add="me"))
    assert me in mm.cc_addrs and me not in mm.confirmations["unverified"]


