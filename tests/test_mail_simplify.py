def _profile(db, case) -> SenderProfile:
    return db.scalar(select(SenderProfile).where(SenderProfile.case_id == case.id))


@pytest.fixture
def contact(db, case):
    """The sender profile's contact e-mail set to an address that is not the case mailbox (restored after)."""
    p = _profile(db, case)
    before = p.contact_email
    p.contact_email = "desk-lead@athena-desk.example"
    db.commit()
    yield p.contact_email
    db.expire_all()
    p = _profile(db, case)
    if p is not None:
        p.contact_email = before
        db.commit()


# --------------------------------------------------------------------------- the sender profile's signature
def test_with_profile_signature_replaces_the_opening_and_the_close_and_keeps_the_footer():
    intro = "We write as Athena Software Group, Inc., on behalf of Jordan Avery, acting under the victim's LoA."
    sig = "Yours faithfully,\n\nAthena Software Group, Inc., on behalf of Jordan Avery"
    out = compose.with_profile_signature(PI_BODY, intro, sig)
    assert compose.PI_FIRM_PHRASE not in out and "Yours respectfully" not in out and "J. Smith" not in out
    assert out.startswith("**Subject:** Freeze request\n\nDear Compliance Team,\n\n" + intro + "\n\n")
    assert "We ask you to freeze the account" in out  # the letter's own text is untouched
    assert sig + "\n\n* * *\n\n*Draft generated by Aegis" in out and out.endswith("Review before sending.*\n")
    assert compose.with_profile_signature(out, intro, sig) == out  # a second click changes nothing
    # no opening and no closing at all: both are added (after the salutation, at the end)
    bare = compose.with_profile_signature("Dear Sirs,\n\nPlease freeze it.\n", intro, sig)
    assert bare == f"Dear Sirs,\n\n{intro}\n\nPlease freeze it.\n\n{sig}\n"


def test_use_the_sender_profiles_signature_is_one_saved_edit(db, case, run, client, client_for, mail):  # noqa: F811
    from app.services import seed_from_fixture

    _drop_profile(db, case)
    old = _draft(db, case, run)  # the PI-firm block
    seed_from_fixture(db)  # the profile is set up again
    db.expire_all()
    corr = db.get(Correspondence, old.id)
    assert compose.sender_check(db, case, corr, mail.settings).fixable
    n_versions = len((corr.meta or {}).get("versions") or [])
    inv = client_for("investigator", case=case)
    r = _compose(inv, case, corr, action="use_signature")
    assert r.status_code == 303 and r.headers["location"].endswith("?done=signature#editor")
    db.expire_all()
    corr = db.get(Correspondence, old.id)
    profile = _profile(db, case)
    flat = compose._flat(compose.markdown_to_text(corr.body_markdown))
    assert compose._flat(f"{profile.org_name}, on behalf of {profile.on_behalf_of}") in flat
    assert compose.PI_FIRM_PHRASE not in flat and "Draft generated by Aegis" in corr.body_markdown
    assert len(corr.meta["versions"]) == n_versions + 1 and corr.meta["versions"][-1]["source"] == "mail_compose"
    assert compose.sender_check(db, case, corr, mail.settings).ok
    audit = db.scalars(select(AuditEvent).where(AuditEvent.object_id == str(corr.id),
                                                AuditEvent.object_type == "correspondence")
                       .order_by(AuditEvent.id.desc())).first()
    assert audit.detail.get("signature_from_profile") is True and "body_markdown" in audit.detail["fields"]
    page = inv.get(f"/cases/{case.id}/authorities/correspondence/{corr.id}/email?done=signature").text
    assert "opens and closes with the sender profile" in page and 'id="mail-sender-warning"' not in page
    r = _compose(inv, case, corr, action="use_signature")
    assert r.headers["location"].endswith("?done=signature_same#editor")
    mm = _prepared(db, _compose(inv, case, db.get(Correspondence, old.id)))
    assert _send(client, case, mm).headers["location"].endswith("?r=sent")  # no acknowledgement needed now


