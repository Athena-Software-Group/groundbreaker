# --------------------------------------------------------------------------- Cc: the sender of record, me
def test_cc_the_sender_of_record_is_ticked_by_default_and_remembered(db, case, run, client, client_for, mail,  # noqa: F811
                                                                     contact):
    corr = _draft(db, case, run)
    inv = client_for("investigator", case=case)
    url = f"/cases/{case.id}/authorities/correspondence/{corr.id}/email"
    page = inv.get(url).text
    assert re.search(r'name="cc_add" value="sender" id="mail-cc-sender"\s+checked', page)
    assert f"Cc the sender of record (<span class=\"mono\">{contact}</span>)" in page
    assert 'name="cc_offered" value="1"' in page
    mm = _prepared(db, _compose(inv, case, corr, cc_offered="1", cc_add="sender"))
    assert contact in mm.cc_addrs and TO in mm.to_addrs
    assert contact not in mm.confirmations["unverified"]  # our own address: the box is the confirmation
    # Edit: back to the editor, the box ticked and the address not repeated as a typed Cc
    path = f"/cases/{case.id}/mail/messages/{mm.id}"
    assert inv.post(f"{path}/edit", data={"csrf_token": csrf_token(inv, path)}).status_code in (200, 303)
    db.expire_all()
    saved = db.get(Correspondence, corr.id).meta["mail_draft"]
    assert saved["cc_add"] == ["sender"] and contact not in saved["cc"]
    page = inv.get(url).text
    assert re.search(r'id="mail-cc-sender"\s+checked', page) and contact not in page.split('id="mail-cc-other"')[0][-400:]
    # unticked and saved: remembered for this letter
    r = _compose(inv, case, db.get(Correspondence, corr.id), action="save", cc_offered="1")
    assert r.status_code == 303
    db.expire_all()
    assert db.get(Correspondence, corr.id).meta["mail_draft"]["cc_add"] == []
    page = inv.get(url).text
    assert 'id="mail-cc-sender"' in page and not re.search(r'id="mail-cc-sender"\s+checked', page)
    mm2 = _prepared(db, _compose(inv, case, db.get(Correspondence, corr.id), cc_offered="1"))
    assert contact not in (mm2.cc_addrs or [])


